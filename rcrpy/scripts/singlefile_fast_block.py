    def _rcrpy_halfSampleMode(y):
        return float(_rcrpy_hsm(np.ascontiguousarray(y, np.float64)))

    def _rcrpy_halfSampleMode_w(w, y):
        w = np.ascontiguousarray(w, np.float64)
        y = np.ascontiguousarray(y, np.float64)
        lo, hi = _rcrpy_hsm_w_window(w, y)
        return float(getMedian_w(w[lo:hi + 1], y[lo:hi + 1]))

    def _rcrpy_get68th_w(w, y):
        idx = np.argsort(y, kind="stable")
        ys = np.ascontiguousarray(y[idx], np.float64)
        ws = np.ascontiguousarray(w[idx], np.float64)
        return float(_rcrpy_g68(ys, ws, float(np.sum(ws))))

    def _rcrpy_getXVec_w(size, w):
        w = np.ascontiguousarray(w, np.float64)
        return _rcrpy_getxvec(size, w, 1.0 / float(np.sum(w)), 2.0)

    def _rcrpy_getFNRatio(x, w):
        counter = int(np.searchsorted(x, 1.0, side="left"))
        if counter == 0:
            return math.nan
        w = np.ascontiguousarray(w, np.float64)
        mean = float(np.sum(w[:counter])) / counter
        st_dev = _cpp_sqrt_div(_rcrpy_fnratio_sumsq(w, counter, mean, 2.0), counter - 1)
        return math.nan if mean == 0.0 else st_dev / mean

    def _rcrpy_fitDL_w(counter, w, x, y, get_fn_w):
        w = np.ascontiguousarray(w, np.float64)
        x = np.ascontiguousarray(x, np.float64)
        y = np.ascontiguousarray(y, np.float64)
        sigma, single_line_fit, delta, short = _rcrpy_fitdl_core(w, x, y)
        if short:
            return single_line_fit
        if delta < get_fn_w(int(counter), x, w):
            return single_line_fit
        return sigma

