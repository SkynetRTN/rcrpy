            mu = _R4_mu_w(mu_code, ones, ty)
            dh = np.empty(cnt, np.float64)
            for i in range(cnt):
                dh[i] = abs(ty[i] - mu)
            last_eq = -1
            for i in range(cnt):
                if _R4_isclose(ty[i], mu):
                    last_eq = i
            nb = 0; na = 0
            for i in range(cnt):
                ic = _R4_isclose(ty[i], mu)
