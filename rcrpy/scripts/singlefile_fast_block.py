    @_njit(cache=True)
    def _rcrpy_seqsum(arr):
        s = 0.0
        for i in range(arr.shape[0]):
            s += arr[i]
        return s

    @_njit(cache=True)
    def _rcrpy_mfinder(low, high, last_x_under_one, increment, w, x, y):
        DBL_MAX = math.inf
        stop = False
        best_m = -1
        m_low = -1
        m_high = -1
        end_r = last_x_under_one + 1
        while not stop:
            min_error = DBL_MAX
            m = low
            while m < high:
                x_at_m = x[m]
                a = 0.0
                e = 0.0
                for i in range(m + 1):
                    wx = w[i] * x[i]
                    a += wx * x[i]
                    e += wx * y[i]
                for i in range(m + 1, end_r):
                    a += (x_at_m * x_at_m) * w[i]
                    e += (x_at_m * w[i]) * y[i]
                b = 0.0
                d = 0.0
                f = 0.0
                for i in range(m + 1, end_r):
                    diff = x[i] - x_at_m
                    b += (x_at_m * w[i]) * diff
                    d += (w[i] * diff) * diff
                    f += (w[i] * y[i]) * diff
                c = b
                if a != 0.0 and (d - c * b) != 0.0:
                    tau = (f - e * c / a) / (d - c * b / a)
                    sigma = (e - tau * b) / a
                    error = 0.0
                    for i in range(m + 1):
                        fl = sigma * x[i] - y[i]
                        error += (w[i] * fl) * fl
                    for i in range(m + 1, end_r):
                        diff = x[i] - x_at_m
                        fr = sigma * x_at_m + tau * diff - y[i]
                        error += (w[i] * fr) * fr
                    if error < min_error:
                        min_error = error
                        best_m = m
                        m_low = max(best_m - increment - 1, 1)
                        m_high = min(best_m + increment + 1, last_x_under_one)
                m += increment
            if increment > 1:
                increment = max(int(math.floor((m_high - m_low) / 6.36)), 1)
            else:
                stop = True
            low = m_low
            high = m_high
        if low == high:
            return low
        return best_m

    @_njit(cache=True)
    def _rcrpy_median(y):
        n = y.shape[0]
        if n <= 1:
            return y[0]
        high = n // 2
        low = high - 1
        total_sum = n
        if n % 2 == 0:
            running_sum = n / 2.0 + 0.5
        else:
            running_sum = n / 2.0
        return y[low] + (0.5 * total_sum - running_sum + 1.0) * (y[high] - y[low])

    @_njit(cache=True)
    def _rcrpy_hsm(y):
        REL_TOL = 1e-8
        n = y.shape[0]
        lo = 0
        hi = n - 1
        lo_in = -1
        hi_in = -1
        while lo != lo_in or hi != hi_in:
            lo_in = lo
            hi_in = hi
            size = hi - lo + 1
            half_window = size // 2
            if half_window == 0:
                break
            m = size - half_window
            min_dist = math.inf
            for i in range(m):
                dd = y[lo + half_window + i] - y[lo + i]
                if dd < min_dist:
                    min_dist = dd
            first_i = -1
            last_i = -1
            for i in range(m):
                dd = y[lo + half_window + i] - y[lo + i]
                if min_dist == 0.0:
                    tied = (dd == 0.0)
                else:
                    tied = abs(dd - min_dist) <= REL_TOL * abs(min_dist)
                if tied:
                    if first_i == -1:
                        first_i = i
                    last_i = i
            new_lo = first_i + lo
            new_hi = last_i + half_window + lo
            lo = new_lo
            hi = new_hi
        return _rcrpy_median(y[lo:hi + 1])

    @_njit(cache=True)
    def _rcrpy_isclose(a, b):
        if abs(a - b) < 2.2250738585072014e-308:
            return True
        d = abs(b) if abs(b) > abs(a) else abs(a)
        if d == 0.0:
            return True
        return abs((a - b) / d) < 1e-8

    @_njit(cache=True)
    def _rcrpy_hsm_w_window(w, y):
        n = y.shape[0]
        lower = 0
        upper = n - 1
        lower_in = -1
        upper_in = -1
        fl = -1
        fu = -1
        while lower != lower_in or upper != upper_in:
            lower_in = lower
            upper_in = upper
            size = upper - lower + 1
            if size <= 1:
                break
            min_dist = 999999.0
            hws = 0.0
            for i in range(lower, upper + 1):
                hws += w[i]
            hws *= 0.5
            s_vec = np.empty(size, dtype=np.float64)
            s = 0.5 * w[lower]
            s_vec[0] = s
            for j in range(1, size):
                s += w[lower + j - 1] * 0.5 + w[lower + j] * 0.5
                s_vec[j] = s
            for i in range(size):
                if s_vec[i] < hws or _rcrpy_isclose(s_vec[i], hws):
                    total = s_vec[i] + hws
                    k = i
                    while k < size and (s_vec[k] < total or _rcrpy_isclose(s_vec[k], total)):
                        k += 1
                    k -= 1
                    dd = abs(y[k + lower] - y[i + lower])
                    if _rcrpy_isclose(dd, min_dist):
                        if i + lower < fl:
                            fl = i + lower
                        if k + lower > fu:
                            fu = k + lower
                    elif dd < min_dist:
                        min_dist = dd
                        fl = i + lower
                        fu = k + lower
                if s_vec[i] > hws or _rcrpy_isclose(s_vec[i], hws):
                    total = s_vec[i] - hws
                    k = i
                    while k > -1 and (s_vec[k] > total or _rcrpy_isclose(s_vec[k], total)):
                        k -= 1
                    k += 1
                    dd = abs(y[i + lower] - y[k + lower])
                    if _rcrpy_isclose(dd, min_dist):
                        if k + lower < fl:
                            fl = k + lower
                        if i + lower > fu:
                            fu = i + lower
                    elif dd < min_dist:
                        min_dist = dd
                        fl = k + lower
                        fu = i + lower
            lower = fl
            upper = fu
        return lower, upper

    @_njit(cache=True)
    def _rcrpy_g68(y_sorted, w_sorted, total_sum):
        n = y_sorted.shape[0]
        if n <= 1:
            return y_sorted[0]
        sum_counter = 0
        running_sum = w_sorted[0] * 0.682689
        while running_sum < 0.682689 * total_sum:
            sum_counter += 1
            running_sum += (w_sorted[sum_counter - 1] * 0.317311
                            + w_sorted[sum_counter] * 0.682689)
        if sum_counter == 0:
            return y_sorted[0]
        denom = w_sorted[sum_counter - 1] * 0.317311 + w_sorted[sum_counter] * 0.682689
        return (y_sorted[sum_counter - 1]
                + (0.682689 * total_sum - (running_sum - denom)) / denom
                * (y_sorted[sum_counter] - y_sorted[sum_counter - 1]))

    @_njit(cache=True)
    def _rcrpy_inverf(x, e2):
        # e2 is a runtime PARAMETER -> real libm pow(t, 2.0) == CPython t**2.
        PI = 3.1415926535897932384626434
        inverf_mult = (8.0 * (PI - 3.0)) / (3 * PI * (4.0 - PI))
        sqrt2 = math.sqrt(2.0)
        x_log = math.log(1.0 - x * x)
        inner = math.pow(2.0 / (PI * inverf_mult) + x_log * 0.5, e2) - x_log / inverf_mult
        return sqrt2 * math.sqrt(-2.0 / (PI * inverf_mult) - x_log * 0.5 + math.sqrt(inner))

    @_njit(cache=True)
    def _rcrpy_getxvec(size, w, inv_w_sum, e2):
        x = np.empty(size, dtype=np.float64)
        s_sum = 0.682689 * w[0]
        x[0] = _rcrpy_inverf(s_sum * inv_w_sum, e2)
        for i in range(1, size):
            s_sum += 0.317311 * w[i - 1] + 0.682689 * w[i]
            x[i] = _rcrpy_inverf(s_sum * inv_w_sum, e2)
        return x

    @_njit(cache=True)
    def _rcrpy_fnratio_sumsq(w, counter, mean, e2):
        s = 0.0
        for i in range(counter):
            d = w[i] - mean
            s += math.pow(d, e2)
        return s

    @_njit(cache=True)
    def _rcrpy_fitdl_core(w, x, y):
        n = x.shape[0]
        if n == 1:
            amount = 0 if x[0] >= 1.0 else 1
        else:
            amount = 0
            while amount < n and x[amount] < 1.0:
                amount += 1
        num = 0.0
        den = 0.0
        for i in range(amount):
            wx = w[i] * x[i]
            num += wx * y[i]
            den += wx * x[i]
        single_line_fit = num / den
        if n < 4:
            return single_line_fit, single_line_fit, 0.0, True
        m = _rcrpy_mfinder(1, amount - 1, amount - 1, max(int(n / 6.36), 1), w, x, y)
        x_at_m = x[m]
        a = 0.0
        e = 0.0
        for i in range(m + 1):
            wx = w[i] * x[i]
            a += wx * x[i]
            e += wx * y[i]
        for i in range(m + 1, amount):
            a += (x_at_m * x_at_m) * w[i]
            e += (x_at_m * w[i]) * y[i]
        b = 0.0
        d = 0.0
        f = 0.0
        for i in range(m + 1, amount):
            diff = x[i] - x_at_m
            b += (x_at_m * w[i]) * diff
            d += (w[i] * diff) * diff
            f += (w[i] * y[i]) * diff
        c = b
        tau = (f - e * c / a) / (d - c * b / a)
        sigma = (e - tau * b) / a
        dle = 0.0
        for i in range(m + 1):
            fl = sigma * x[i] - y[i]
            dle += (w[i] * fl) * fl
        for i in range(m + 1, amount):
            diff = x[i] - x_at_m
            fr = sigma * x_at_m + tau * diff - y[i]
            dle += (w[i] * fr) * fr
        sle = 0.0
        for i in range(amount):
            ef = single_line_fit * x[i] - y[i]
            sle += (w[i] * ef) * ef
        numd = sle - dle
        if dle != 0.0:
            delta = numd / dle
        elif numd > 0.0:
            delta = math.inf
        elif numd < 0.0:
            delta = -math.inf
        else:
            delta = math.nan
        if sigma < 0:
            sigma = 1e-10
        return sigma, single_line_fit, delta, False

