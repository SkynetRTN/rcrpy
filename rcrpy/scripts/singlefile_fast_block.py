# Optional Numba acceleration (BIT-EXACT kernels; auto-enabled if numba is
# importable). Compiles the double-line core (fitDL_w) and its leaves — the
# inverse-erf x-vector, weighted m-finder, half-sample mode (both branches),
# 68th-percentile, FN ratio, and the C++-exact sequential sum — so the inner
# double-line runs end-to-end in nopython. Results are BIT-IDENTICAL to the
# pure-Python reference above (a parity battery's mu/sigma diff stays exactly
# 0). The transcendental kernels (inverf, getFNRatio) are bit-exact too: the
# `**2` exponent is threaded as a runtime function PARAMETER so Numba emits a
# real libm pow() (== CPython t**2) instead of folding to a multiply (~1 ULP
# drift). Numba's math.log/sqrt already match CPython's libm bit-for-bit.
#
# njit functions are MODULE-LEVEL with cache=True: numba can only cache
# top-level functions, and caching persists the compiled code to disk so a
# one-shot deployment doesn't recompile every kernel on every process (the
# first run compiles + caches; later runs load from disk).
#
# Falls back to pure Python if numba is absent. Set env RCRPY_NO_FAST=1 to
# force the pure-Python path (e.g. to use this file as the parity oracle).
# fitDL_w's get_fn_w (technique FN/CF model) stays in Python — it's the only
# transcendental that varies per technique and is called once per fitDL_w
# (bounded), not in the inner sum loops. Generated by build_single_file.py.
# ============================================================================
